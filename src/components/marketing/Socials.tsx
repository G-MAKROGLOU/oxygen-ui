const SIZE = { sm: 'h-8 w-8', md: 'h-10 w-10' }

const VARIANT = {
    ghost: 'text-foreground-secondary hover:bg-surface-raised hover:text-foreground',
    solid: 'bg-surface-raised text-foreground-secondary hover:bg-accent hover:text-accent-fg',
    outline: 'border border-border text-foreground-secondary hover:border-border-strong hover:text-foreground',
}

/**
 * A row of social / contact icon links. Pass `platform` for a built-in brand
 * glyph (x, github, linkedin, youtube, instagram, facebook, mastodon, email,
 * website) or supply your own `icon`. Each link is a labelled, focusable anchor.
 *
 * @example
 * <Socials links={[
 *   { platform: 'github', href: 'https://github.com/acme' },
 *   { platform: 'linkedin', href: 'https://linkedin.com/company/acme' },
 *   { platform: 'email', href: 'mailto:hi@acme.com' },
 * ]} />
 */
export default function Socials({
    links,
    variant = 'ghost',
    size = 'md',
    newTab = true,
    'aria-label': ariaLabel = 'Social links',
    className = '',
    style,
}: SocialsProps) {
    return (
        <nav aria-label={ariaLabel} className={cx('flex flex-wrap items-center gap-2', className)} style={style}>
            {links.map((link, i) => {
                const label = link.label ?? (link.platform ? link.platform[0].toUpperCase() + link.platform.slice(1) : 'Link')
                const icon = link.icon ?? (link.platform ? ICONS[link.platform] : null)
                const ext = newTab && !link.href.startsWith('mailto:')
                return (
                    <a
                        key={i}
                        href={link.href}
                        aria-label={label}
                        title={label}
                        {...(ext ? { target: '_blank', rel: 'noopener noreferrer' } : {})}
                        className={['flex items-center justify-center rounded-full transition-colors duration-150 focus:outline-none focus-visible:ring-2 focus-visible:ring-accent', SIZE[size], VARIANT[variant]].join(' ')}
                    >
                        {icon}
                    </a>
                )
            })}
        </nav>
    )
}
